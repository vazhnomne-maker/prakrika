    def загрузить_темы(self):
        """Загружает темы и метафоры из файла"""
        try:
            with open(self.файл_тем, 'r', encoding='utf-8') as f:
                содержание = f.read()
            
            # Парсим темы и метафоры
            строки = содержание.split('\n')
            текущая_тема = None
            текущие_метафоры = []
            
            for строка in строки:
                # Ищем номер темы
                match_тема = re.match(r'^(\d+)\.\s+"(.+)"', строка.strip())
                if match_тема:
                    # Сохраняем предыдущую тему
                    if текущая_тема is not None:
                        self.темы.append(текущая_тема)
                        self.метафоры_по_темам[текущая_тема['номер']] = текущие_метафоры
                    
                    номер = int(match_тема.group(1))
                    текст = match_тема.group(2)
                    текущая_тема = {'номер': номер, 'текст': текст}
                    текущие_метафоры = []
                
                # Ищем метафоры
                elif 'Выражения и метафоры чувств:' in строка:
                    части = строка.split('Выражения и метафоры чувств:')
                    if len(части) > 1:
                        метафоры_текст = части[1].strip()
                        текущие_метафоры = [м.strip() for м in метафоры_текст.split(',') if м.strip()]
            
            # Добавляем последнюю тему
            if текущая_тема is not None:
                self.темы.append(текущая_тема)
                self.метафоры_по_темам[текущая_тема['номер']] = текущие_метафоры
            
            print(f"Загружено тем: {len(self.темы)}")
            return True
            
        except Exception as e:
            print(f"Ошибка загрузки тем: {e}")
            return False
    
