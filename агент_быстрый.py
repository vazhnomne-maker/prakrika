#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Быстрый агент для создания стиха по конкретному номеру темы
Использование: python агент_быстрый.py <номер_темы>
"""

import os
import sys
import re
from datetime import datetime

class БыстрыйПоэт:
    """Упрощенный агент для быстрого создания стихов"""
    
    def __init__(self):
        self.папка = r"D:\Kiro_projekt\ptaktika"
        self.файл_тем = os.path.join(self.папка, "женские_посты_о_проблемах_структурировано.txt")
        self.темы = {}
        
    def загрузить_тему(self, номер):
        """Загружает конкретную тему по номеру"""
        try:
            with open(self.файл_тем, 'r', encoding='utf-8') as f:
                содержание = f.read()
            
            # Ищем конкретную тему
            шаблон = rf'{номер}\.\s+"(.+?)"\s*\n\s*Выражения и метафоры чувств:\s*(.+?)(?=\n\d+\.|$)'
            match = re.search(шаблон, содержание, re.DOTALL)
            
            if match:
                текст_темы = match.group(1).strip()
                метафоры_текст = match.group(2).strip()
                метафоры = [м.strip() for м in метафоры_текст.split(',') if м.strip()]
                
                return {
                    'номер': номер,
                    'текст': текст_темы,
                    'метафоры': метафоры
                }
            else:
                print(f"Тема №{номер} не найдена")
                return None
                
        except Exception as e:
            print(f"Ошибка загрузки темы: {e}")
            return None
    
    def создать_стих(self, тема_данные):
        """Создает стих по данным темы"""
        if not тема_данные:
            return None
        
        номер = тема_данные['номер']
        текст = тема_данные['текст']
        метафоры = тема_данные['метафоры']
        
        # Шаблоны для стиха
        куплеты = [
            # Куплет 1
            f"В квартире тишина, а в душе — вой,\n{метафоры[0] if метафоры else 'Пустота'} — вот приговор судьбы слепой.\nЯ смотрю в окно, где дождь стучит в стекло,\nА ты где-то там, где мне уже не светло.",
            
            # Куплет 2  
            f"Мы {метафоры[1] if len(метафоры) > 1 else 'строили картинку'} для чужих глаз,\nГде каждый кадр — обман, театр, приказ.\nТы {метафоры[2] if len(метафоры) > 2 else 'искал ракурсы'}, я искала смысл,\nА нашли лишь боль, что в сердце, как нарыв.",
            
            # Куплет 3
            f"Теперь {метафоры[3] if len(метафоры) > 3 else 'листаю прошлое'} — сплошная ложь,\nГде счастье было маской, что не сможешь снять.\nМы думали — {метафоры[4] if len(метафоры) > 4 else 'притворимся'}, и станет правдой,\nА вышло — разрушили, что было однажды."
        ]
        
        припев = f"И {метафоры[0] if метафоры else 'ЭТА БОЛЬ'} — КАК НОЖ ОСТРЫЙ В ГРУДИ,\nГДЕ КАЖДЫЙ ВЗДОХ — КАК ПРИЗНАНИЕ В БЕДЕ.\nМЫ {метафоры[1] if len(метафоры) > 1 else 'ЛГАЛИ ДРУГ ДРУГУ'}, ЧТОБ САМИМ ПОВЕРИТЬ,\nЧТО МОЖНО БЫТЬ СЧАСТЛИВЫМИ В ЭТОЙ ВЕРИГЕ.\nНО {метафоры[2] if len(метафоры) > 2 else 'ПРАВДА'} НЕ СТИРАЕТСЯ, КАК СЛЕД,\nОНА ОСТАЕТСЯ В ДУШЕ НАВСЕГДА.\nМЫ {метафоры[3] if len(метафоры) > 3 else 'СТРОИЛИ ЗАМКИ'} ИЗ ПЕСКА,\nА ПОЛУЧИЛИ — {метафоры[4] if len(метафоры) > 4 else 'РАЗБИТОЕ СЕРДЦЕ'} И ТОСКА."
        
        # Формируем результат
        результат = f"ТЕМА: №{номер}\n"
        результат += f"{текст}\n\n"
        результат += f"ВЫРАЖЕНИЯ И МЕТАФОРЫ ЧУВСТВ:\n"
        результат += f"{', '.join(метафоры)}\n\n"
        результат += "="*60 + "\n\n"
        
        for i, куплет in enumerate(куплеты, 1):
            результат += f"КУПЛЕТ {i}\n"
            результат += куплет + "\n\n"
        
        результат += "ПРИПЕВ\n"
        результат += припев + "\n\n"
        результат += "="*60 + "\n"
        результат += f"Стих создан по теме №{номер}\n"
        результат += f"Дата: {datetime.now().strftime('%d.%m.%Y %H:%M')}"
        
        return результат
    
    def сохранить_стих(self, номер, стих):
        """Сохраняет стих в файл"""
        if not стих:
            return False
        
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        имя_файла = f"стих_тема{номер}_{timestamp}.txt"
        путь_файла = os.path.join(self.папка, имя_файла)
        
        try:
            with open(путь_файла, 'w', encoding='utf-8') as f:
                f.write(стих)
            print(f"\n✓ Стих сохранен в файл: {имя_файла}")
            return True
        except Exception as e:
            print(f"✗ Ошибка сохранения: {e}")
            return False
    
    def выполнить(self, номер_темы):
        """Основная функция выполнения"""
        print(f"\nСоздание стиха по теме №{номер_темы}...")
        
        # Загружаем тему
        тема = self.загрузить_тему(номер_темы)
        if not тема:
            return False
        
        print(f"Тема: {тема['текст'][:80]}...")
        print(f"Метафоры: {', '.join(тема['метафоры'][:3])}...")
        
        # Создаем стих
        стих = self.создать_стих(тема)
        if not стих:
            print("Не удалось создать стих")
            return False
        
        # Показываем стих
        print("\n" + "="*60)
        print("СОЗДАННЫЙ СТИХ:")
        print("="*60)
        print(стих)
        
        # Сохраняем
        self.сохранить_стих(номер_темы, стих)
        
        return True


def main():
    """Точка входа"""
    if len(sys.argv) != 2:
        print("Использование: python агент_быстрый.py <номер_темы>")
        print("Пример: python агент_быстрый.py 15")
        sys.exit(1)
    
    try:
        номер_темы = int(sys.argv[1])
        if not (1 <= номер_темы <= 30):
            print("Номер темы должен быть от 1 до 30")
            sys.exit(1)
    except ValueError:
        print("Номер темы должен быть числом")
        sys.exit(1)
    
    агент = БыстрыйПоэт()
    успех = агент.выполнить(номер_темы)
    
    if успех:
        print("\n✓ Готово!")
    else:
        print("\n✗ Завершено с ошибками")


if __name__ == "__main__":
    main()